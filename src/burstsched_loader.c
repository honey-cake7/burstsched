/*
 * burstsched_loader.c — User-space loader for the BurstSched BPF
 *                        scheduler.  Opens the skeleton, sets feature
 *                        flags, attaches the struct_ops, and waits.
 *
 * Usage:
 *   ./burstsched_loader [--feature <name>]...
 *
 * Features (match ablation table rows):
 *   reactive_mlfq      (always on — baseline)
 *   ewma               enable EWMA predictor integration
 *   learned            enable learned predictor integration
 *   confidence_gate    enable confidence-gated placement
 *   predicted_slices   enable predicted time slices
 *   wakeup_preempt     enable wakeup preemption
 *   per_cpu            enable per-CPU queue stubs
 *
 * Build: cc -o burstsched_loader burstsched_loader.c \
 *          -lbpf -lelf -lz -I../include
 *
 * NOTE: Requires libbpf and the generated skeleton header.
 *       Will not compile on Windows — scaffolded for Linux 6.12+.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <unistd.h>
#include <errno.h>

#include <bpf/libbpf.h>
#include <bpf/bpf.h>

#include "burstsched_common.h"

/* The skeleton header is auto-generated by bpftool from burstsched.bpf.o */
