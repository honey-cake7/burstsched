/* ================================================================== */
/*  Signal handling for clean shutdown                                 */
/* ================================================================== */

static volatile sig_atomic_t running = 1;

static void sig_handler(int sig)
{
    (void)sig;
    running = 0;
}

/* ================================================================== */
/*  Feature-flag parsing                                               */
/* ================================================================== */

struct feature_map {
    const char *name;
    __u32       flag;
};

static const struct feature_map features[] = {
    { "reactive_mlfq",    FEAT_REACTIVE_MLFQ    },
    { "ewma",             FEAT_EWMA             },
    { "learned",          FEAT_LEARNED           },
    { "confidence_gate",  FEAT_CONFIDENCE_GATE   },
    { "predicted_slices", FEAT_PREDICTED_SLICES  },
    { "wakeup_preempt",   FEAT_WAKEUP_PREEMPT   },
    { "per_cpu",          FEAT_PER_CPU           },
};

static __u32 parse_features(int argc, char **argv)
{
    __u32 flags = 0;

    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--feature") == 0 && i + 1 < argc) {
            i++;
            int found = 0;
            for (size_t f = 0; f < sizeof(features)/sizeof(features[0]); f++) {
                if (strcmp(argv[i], features[f].name) == 0) {
                    flags |= features[f].flag;
                    found = 1;
                    printf("[loader] enabling feature: %s (0x%02x)\n",
                           features[f].name, features[f].flag);
                    break;
                }
            }
            if (!found) {
                fprintf(stderr, "[loader] unknown feature: %s\n", argv[i]);
                exit(EXIT_FAILURE);
            }
        } else if (strcmp(argv[i], "--help") == 0 || strcmp(argv[i], "-h") == 0) {
            printf("Usage: %s [--feature <name>]...\n", argv[0]);
            printf("\nAvailable features:\n");
            for (size_t f = 0; f < sizeof(features)/sizeof(features[0]); f++)
                printf("  %-20s 0x%02x\n", features[f].name, features[f].flag);
            exit(EXIT_SUCCESS);
        }
    }

    return flags;
}

/* ================================================================== */
/*  Main                                                               */
/* ================================================================== */

int main(int argc, char **argv)
{
    __u32 flags = parse_features(argc, argv);

    printf("[loader] BurstSched loader starting, feature flags = 0x%02x\n", flags);
    printf("[loader] reactive_mlfq is always on (baseline)\n");

    signal(SIGINT,  sig_handler);
    signal(SIGTERM, sig_handler);

    /*
     * === BPF lifecycle (requires Linux + libbpf + skeleton) ===
     *
     * struct burstsched *skel = burstsched__open();
     * if (!skel) { perror("open"); return 1; }
     *
     * // Set the global feature-flag variable before loading.
     * skel->rodata->enabled_features = flags;
     *
     * int err = burstsched__load(skel);
     * if (err) { perror("load"); burstsched__destroy(skel); return 1; }
     *
     * // Attach the struct_ops — this activates the scheduler.
     * struct bpf_link *link = bpf_map__attach_struct_ops(skel->maps.burstsched_ops);
     * if (!link) { perror("attach"); burstsched__destroy(skel); return 1; }
     *
     * printf("[loader] scheduler attached — Ctrl-C to unload\n");
     *
     * while (running)
     *     sleep(1);
     *
     * printf("[loader] unloading scheduler\n");
     * bpf_link__destroy(link);
     * burstsched__destroy(skel);
     */

    fprintf(stderr,
        "[loader] skeleton not yet generated — "
        "build on Linux with: make skeleton\n");

    printf("[loader] feature flags that would be set: 0x%02x\n", flags);
    printf("[loader] exiting (stub mode)\n");

    return 0;
}
